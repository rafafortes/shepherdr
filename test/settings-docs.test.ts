// docs/settings.md is hand-written while the settings grow, so a new key can ship with no page for the operator to find
// it. Walk the real rows — the CATALOG's, plus the two a space's Settings adds after it — and require every key's own
// name in the doc. A key the doc names in words instead goes in DOC_ALIASES with the words used there, so the exception
// is written down and checked, never a silent blanket skip.
import { describe, expect, test } from 'bun:test'
import { CATALOG, repositorySection, Settings } from '../server/live/settings.ts'

const doc = await Bun.file(new URL('../docs/settings.md', import.meta.url)).text()
/** the keys as separate words: a match inside `advisor.fallbackModel` is not a mention of `advisor.fallback`, and a
 *  trailing full stop after a key in prose is punctuation, not part of it */
const mentioned = (text: string) =>
  new Set(
    text
      .split(/[^A-Za-z0-9_.-]+/)
      .map((w) => w.replace(/[.-]+$/, ''))
      .filter(Boolean),
  )

/** every key the app offers: the CATALOG's rows (backup rows generated by chainRows, which a source-text scan misses)
 *  and the two keys added only for a space — its HEARTBEAT.md row and its Repository section's base branch */
const settings = new Settings({ everywhere: {}, machine: {}, spaces: {} })
const keys = [
  ...new Set([
    ...CATALOG.flatMap((s) => s.rows.map((r) => r.key)),
    ...settings
      .sections([], [], null, 'host', ['space'], 'host', () => 'x')
      .flatMap((s) => s.rows.map((r) => r.key))
      .filter((k) => k === 'heartbeat.md'),
    ...repositorySection('p:host:space', 'host', 'main').rows.map((r) => r.key),
  ]),
]

/** Keys the doc names in words rather than by their key, with the words that name them. The space's Checklist row is
 *  the HEARTBEAT.md file, not a value; [Autopilot](autopilot.md) has its page. Every other key is written in the doc. */
const DOC_ALIASES: Record<string, string> = {
  'heartbeat.md': 'HEARTBEAT.md',
}

/** keys in `list` that have no mention in `text` and no alias. A dotted key is matched as a whole word, so a longer key
 *  does not satisfy it; a bare key like `alerts` must be written as a key, in backticks, or ordinary prose passes it. */
const undocumented = (list: string[], text: string, aliases: Record<string, string>) =>
  list.filter((key) => !(key in aliases) && !(key.includes('.') ? mentioned(text).has(key) : text.includes(`\`${key}\``)))

describe('docs/settings.md names every setting key', () => {
  test('the walk covers generated rows and the two keys a space adds', () => {
    expect(keys.length).toBeGreaterThan(50)
    for (const key of ['task.fallback5Effort', 'heartbeat.md', 'space.base', 'voice.service']) expect(keys).toContain(key)
  })

  test('every key appears in the doc, or has an alias that does', () => {
    expect(undocumented(keys, doc, DOC_ALIASES)).toEqual([])
  })

  test('the aliases name only real keys, and the words they stand for are in the doc', () => {
    for (const [key, name] of Object.entries(DOC_ALIASES)) {
      expect(keys.includes(key)).toBe(true)
      expect(mentioned(doc).has(name.replace(/`/g, ''))).toBe(true)
    }
  })

  test('a key the app adds without a doc mention is reported, and prose or a longer key is not one', () => {
    expect(undocumented(['task.agent', 'brand.new.key'], '# Settings\n`task.agent`', {})).toEqual(['brand.new.key'])
    expect(undocumented(['advisor.fallback'], '`advisor.fallbackModel`', {})).toEqual(['advisor.fallback'])
    expect(undocumented(['alerts'], 'the alerts are told, not keyed', {})).toEqual(['alerts'])
    expect(undocumented(['brand.new.key'], '# Settings', { 'brand.new.key': 'the new key' })).toEqual([])
  })
})
